"""Dump per-request attention batch shapes for micro-benchmark replay.

When ``VLLM_TRITON_ATTN_DUMP_SHAPES=1`` the ``TritonAttentionMetadataBuilder``
records every batch's per-request ``query_lens`` / ``seq_lens`` and writes a
``benchmark_paged_attention.py`` ``capture_batches`` JSON on interpreter exit.
This lets real serving traffic be replayed as micro-benchmarks.
"""

import atexit
import json
import os
import threading

import torch

import vllm.envs as envs
from vllm.logger import init_logger

logger = init_logger(__name__)


def _rle(values: list[int]) -> list[list[int]]:
    """Run-length encode a list into [value, count] pairs."""
    pairs: list[list[int]] = []
    for v in values:
        if pairs and pairs[-1][0] == v:
            pairs[-1][1] += 1
        else:
            pairs.append([v, 1])
    return pairs


class _ShapeDumper:
    """Collects unique attention batch shapes and writes them once at exit."""

    def __init__(self, path: str, dedup: bool):
        self.path = path
        self.dedup = dedup
        self._lock = threading.Lock()
        # signature -> entry dict (dedup mode), or ordered list (append mode)
        self._entries: dict[tuple, dict] = {}
        self._ordered: list[dict] = []
        self._meta: dict | None = None
        self._min_num_blocks = 0
        atexit.register(self.flush)

    def set_meta(self, meta: dict) -> None:
        if self._meta is None:
            self._meta = meta

    def record(
        self,
        query_lens: list[int],
        seq_lens: list[int],
        capture_max_query_len: int,
        min_num_blocks: int,
    ) -> None:
        sig = (tuple(query_lens), tuple(seq_lens), capture_max_query_len)
        with self._lock:
            self._min_num_blocks = max(self._min_num_blocks, min_num_blocks)
            if self.dedup:
                entry = self._entries.get(sig)
                if entry is not None:
                    entry["count"] += 1
                    return
                entry = {
                    "name": f"batch_{len(self._entries)}",
                    "query_lens_rle": _rle(query_lens),
                    "seq_lens_rle": _rle(seq_lens),
                    "capture_max_query_len": capture_max_query_len,
                    "count": 1,
                }
                self._entries[sig] = entry
            else:
                self._ordered.append(
                    {
                        "name": f"batch_{len(self._ordered)}",
                        "query_lens_rle": _rle(query_lens),
                        "seq_lens_rle": _rle(seq_lens),
                        "capture_max_query_len": capture_max_query_len,
                    }
                )

    def flush(self) -> None:
        with self._lock:
            batches = (
                list(self._entries.values()) if self.dedup else self._ordered
            )
            if not batches or self._meta is None:
                return
            doc = {
                "_comment": (
                    "Auto-generated by TritonAttentionMetadataBuilder shape dump "
                    "(VLLM_TRITON_ATTN_DUMP_SHAPES). Replay with "
                    "benchmark_paged_attention.py --config <this file>."
                ),
                "capture_accurate": True,
                **self._meta,
                "num_blocks": max(self._meta["num_blocks"], self._min_num_blocks),
                "warmup": 20,
                "rep": 100,
                "use_cuda_graphs": True,
                "variants": ["triton_auto", "triton_2d"],
                "capture_batches": batches,
            }
            tmp = f"{self.path}.tmp.{os.getpid()}"
            with open(tmp, "w") as f:
                json.dump(doc, f, indent=2)
            os.replace(tmp, self.path)
            logger.info(
                "Wrote %d attention batch shapes to %s", len(batches), self.path
            )


_dumper: _ShapeDumper | None = None
_dumper_lock = threading.Lock()


def _get_dumper() -> _ShapeDumper:
    global _dumper
    if _dumper is None:
        with _dumper_lock:
            if _dumper is None:
                _dumper = _ShapeDumper(
                    envs.VLLM_TRITON_ATTN_DUMP_PATH,
                    envs.VLLM_TRITON_ATTN_DUMP_DEDUP,
                )
    return _dumper


def maybe_dump_shapes(
    common_attn_metadata,
    num_query_heads: int,
    num_kv_heads: int,
    head_size: int,
    block_size: int,
    num_blocks: int,
    dtype: torch.dtype,
) -> None:
    """Record one batch's per-request shapes if dumping is enabled.

    Reads ``query_start_loc_cpu`` (already on host) to derive per-request query
    lengths and copies ``seq_lens`` to host. Only invoked when the env flag is
    set, so it adds no overhead to normal runs.
    """
    qsl = common_attn_metadata.query_start_loc_cpu
    query_lens = (qsl[1:] - qsl[:-1]).tolist()
    seq_lens = common_attn_metadata.seq_lens.cpu().tolist()

    dumper = _get_dumper()
    dumper.set_meta(
        {
            "num_query_heads": num_query_heads,
            "num_kv_heads": num_kv_heads,
            "head_size": head_size,
            "block_size": block_size,
            "num_blocks": num_blocks,
            "dtype": str(dtype).removeprefix("torch."),
        }
    )
    dumper.record(
        [int(x) for x in query_lens],
        [int(x) for x in seq_lens],
        int(common_attn_metadata.max_query_len),
        _min_blocks(seq_lens, block_size),
    )


def _min_blocks(seq_lens: list[int], block_size: int) -> int:
    """Blocks the benchmark needs for this batch: one row per request sized to
    the longest sequence (see build_attention_inputs_from_requests)."""
    if not seq_lens:
        return 0
    max_seq_len = max(int(s) for s in seq_lens)
    blocks_per_seq = (max_seq_len + block_size - 1) // block_size
    return len(seq_lens) * blocks_per_seq
